"""
Write data/universe/label_map.csv from the owner-ruled draft (HANDOFF task 55, decisions/0054, 0057).

    python scripts/build_label_map.py [--draft PATH] [--out PATH]

The draft (`Claude outputs/label_map_draft_2026-10-11.csv`) carries no owner correction; its sha256
must begin `6de22793765f2a24` or this refuses. The map has a row for every draft row whose tier is
not `tradable-only`. After the map is committed it is the owner's record and the draft is not read
again; this script exists so the committed file can be regenerated byte for byte.

Holds labels only: no vendor value, no price. Nothing here reads data/raw/ or a date.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAFT = ROOT / "Claude outputs" / "label_map_draft_2026-10-11.csv"
OUT = ROOT / "data" / "universe" / "label_map.csv"
DRAFT_SHA_PREFIX = "6de22793765f2a24"

COLUMNS = (
    "ticker",
    "asset_group",
    "reporting_class",
    "region",
    "region_view",
    "curve_currency",
    "rating_class",
    "market_label",
    "curve",
    "rating",
    "hy_bucket",
    "market",
)

# decisions/0057, "The vocabulary a scope needs": verbatim label -> normalised value.
CURVE = {
    "USD": "USD",
    "USD real": "USD_real",
    "EUR": "EUR",
    "GBP": "GBP",
    "JPY": "JPY",
    "European, several (mostly EUR)": "EUR_multi",
    "Several (EUR, JPY, GBP and others)": "DM_multi",
    "EM local, several": "EM_local_multi",
}
RATING = {
    "Government": "Government",
    "Government (bills)": "Government",
    "Government, inflation-linked": "Government",
    "Government, mixed IG and HY": "Government",
    "Agency MBS": "Agency",
    "Aggregate, IG": "Aggregate",
    "Aggregate, IG (mostly government)": "Aggregate",
    "IG": "IG",
    "HY Ba": "HY",
    "HY B": "HY",
    "HY Caa": "HY",
    "HY, all ratings": "HY",
    "Mixed IG and HY": "Mixed",
}
HY_BUCKET = {"HY Ba": "Ba", "HY B": "B", "HY Caa": "Caa", "HY, all ratings": "all"}
MARKET = {"DM": "DM", "DM, with some EM": "DM", "EM": "EM"}

EQUITY_GROUPS = ("equity", "real_asset_equity")
COMMODITIES_DRAFT = "(Commodities bucket)"


def _lookup(table: dict[str, str], value: str, column: str, ticker: str) -> str:
    try:
        return table[value]
    except KeyError:
        raise ValueError(
            f"{ticker}: the {column} label {value!r} is not in decisions/0057's vocabulary table"
        ) from None


def build_rows(draft_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    rows = []
    for d in draft_rows:
        if d["tier"] == "tradable-only":
            continue
        ticker = d["ticker"]
        region = "Commodities" if d["region"] == COMMODITIES_DRAFT else d["region"]
        view = d["asset_group"] in EQUITY_GROUPS and region != "Global"
        row = dict.fromkeys(COLUMNS, "")
        row.update(
            ticker=ticker,
            asset_group=d["asset_group"],
            reporting_class=d["reporting_class"],
            region=region,
            region_view="yes" if view else "no",
        )
        if d["curve_currency"]:
            row.update(
                curve_currency=d["curve_currency"],
                rating_class=d["rating_class"],
                market_label=d["market"],
                curve=_lookup(CURVE, d["curve_currency"], "curve currency", ticker),
                rating=_lookup(RATING, d["rating_class"], "rating class", ticker),
                hy_bucket=HY_BUCKET.get(d["rating_class"], ""),
                market=_lookup(MARKET, d["market"], "market", ticker),
            )
        rows.append(row)
    return rows


def write(rows: list[dict[str, str]], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--draft", type=Path, default=DRAFT)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    digest = hashlib.sha256(args.draft.read_bytes()).hexdigest()
    if not digest.startswith(DRAFT_SHA_PREFIX):
        print(f"refusing: the draft hashes to {digest[:16]}, not {DRAFT_SHA_PREFIX}")
        return 1
    with open(args.draft, newline="", encoding="utf-8-sig") as fh:
        rows = build_rows(list(csv.DictReader(fh)))
    write(rows, args.out)
    print(f"wrote {len(rows)} rows to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
